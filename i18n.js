  function normalize(value) {
    const code = String(value || '').toLowerCase().slice(0, 2);
    return LANGUAGES.includes(code) ? code : 'en';
  }

  // 문구 하나를 꺼낸다. 그 언어에 없으면 첫 번째 언어, 그래도 없으면 열쇠를 그대로 돌려준다
  function t(lang, key, ...args) {
    const table = STRINGS[lang] || STRINGS[LANGUAGES[0]];
    let text = table[key];
    if (typeof text !== 'string') text = STRINGS[LANGUAGES[0]][key];
    if (typeof text !== 'string') return key;
    return text.replace(/\{(\d)\}/g, (_, i) => (args[i] == null ? '' : String(args[i])));
  }

  // 한 언어에 묶인 t를 만든다
  function bind(lang) {
    const fixed = LANGUAGES.includes(lang) ? lang : LANGUAGES[0];
    return (key, ...args) => t(fixed, key, ...args);
  }

  return { LANGUAGES, LANGUAGE_NAMES, STRINGS, normalize, t, bind };
